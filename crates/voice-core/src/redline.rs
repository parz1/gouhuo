//! 红线。
//!
//! 放在 voice-core 里是因为它是**全项目**的策略，不属于某一个探针：
//! latency-probe（M1，协议链路）和 device-probe（M2，设备 + APM）都对着同一组数字。
//!
//! # 这些数字是干什么用的
//!
//! 目标只有三句话：**好用、延迟低、占用低到不影响游戏表现。**
//! 下面的数字是为这三句话服务的，不是反过来。
//!
//! 所以这里把两种东西**分开**，它们的性质完全不同：
//!
//! - **产品线**（`*_MS` / `*_KBPS` / `*_PCT` / `*_MB`）：对用户的承诺。
//!   定它的依据是「用户感知得到吗」和「同类产品在什么水平」，不是我们能做到多少。
//!
//! - **防回归闸**（`GATE_*`）：CI 拿来卡的线，定在**当前实测值 + 一点余量**。
//!   它的唯一作用是「谁改代码让它变慢了，CI 立刻亮」。
//!   产品线松，不代表可以一路劣化下去 —— 那是两件事。
//!
//! 第一版把这两件事混成一组「破线算 bug」的数字，结果是 M2 测完发现端到端
//! 91.9 ms 破了 80 ms 的线，而那 80 ms 本身没有依据。真正该问的是
//! 「91.9 ms 用户能不能接受」，答案是能。所以放开产品线，同时把防回归闸收紧到
//! 实测值附近 —— 这比一条拍脑袋的线有用得多。

// ===========================================================================
// 产品线：对用户的承诺
// ===========================================================================

/// 端到端延迟（同城），毫秒。嘴到耳，含设备和 APM。
///
/// 定 120 的依据：
/// - ITU-T G.114 把单向嘴到耳 150 ms 划为「用户很满意」的上界，超过才开始
///   影响自然对话。120 留了一档余量给真实公网的重尾
/// - Discord / TeamSpeak 在同类配置（共享模式 + AEC）下普遍在 100–150 ms
/// - M2 实测 91.9 ms，已经比它们好
///
/// 换句话说：120 是「明显比现有产品好、且用户感觉不到延迟」的线，
/// 不是「我们能做到的极限」。极限是另一回事，见 `GATE_PROTOCOL_MS` 的注释。
pub const E2E_MS: f64 = 120.0;

/// 通话中 CPU，单核占比 %。
///
/// 放到 6 是因为真正要守的是「不影响游戏表现」，而 3% 和 6% 在这件事上没区别：
/// 8 核机器上 6% 单核 = 0.75% 总量，游戏帧率上根本看不出来。
///
/// **但 CPU 百分比本身不是「影响游戏表现」的好指标。** 真正的风险是
/// 我们的音频线程跑在 TIME_CRITICAL 优先级上（`clock::boost_current_thread`），
/// 而且在等节拍时会自旋。平均占用很低，却可能在游戏的关键帧上抢走一个核心的
/// 几百微秒，表现为偶发掉帧。这个必须在 M6 用真游戏实测帧时间（#12），
/// 光看这个百分比是看不出来的。
pub const CPU_PCT: f64 = 6.0;

/// 静音时带宽（DTX 生效），kbps。
///
/// **这条不放。** 场景是「常驻一个频道挂几小时」，不说话的时候就该接近零流量 ——
/// 这是「不打扰人」的直接体现，也是跟一直在传数据的产品拉开差距的地方。
/// 实测 1.2 kbps，本来就轻松达标，没有放的理由。
pub const SILENT_KBPS: f64 = 5.0;

/// 说话时单条上行带宽，kbps。
///
/// 音质优先的 64 kbps / 10 ms 配置，IPv4 预算约 109.6 kbps。
/// 原先 80 kbps 上限只容得下 32 kbps 编码，不能继续约束高清默认配置。
/// 120 给平均 VBR 码率留余量，不是逐包峰值限制。20 路同时说话约 2.4 Mbps。
pub const SPEAKING_KBPS: f64 = 120.0;

/// voice-core 常驻内存，MB。
///
/// 从 60 放到 100：60 是拍的，而现在 libwebrtc 的 APM 也进来了，它自己有一堆
/// 滤波器状态。100 MB 对一个常驻后台的语音内核仍然是很克制的数字
/// （Discord 动辄几百 MB 到 1 GB）。
///
/// M6 实测（#11）：**整个客户端进程**在频道里 73.0 MB（见
/// [`MEASURED_CLIENT_IN_CHANNEL_RSS_MB`]），语音那一半约 13 MB（减掉登录页的 60 MB）。
/// 离线很远，不用拆进程。线先不收：这是产品线，是对用户的承诺，不是防回归闸。
pub const VOICE_CORE_RSS_MB: f64 = 100.0;

/// 安装包，MB。
///
/// 从 30 放到 60。libwebrtc 的 APM 静态库 strip 之后 38 MB —— 链接器会丢掉
/// 用不到的部分，真正进二进制的通常是几 MB，但 30 MB 这条线在加进 APM 之后
/// 风险不小。60 MB 对比 Discord 的安装包仍然很轻。
///
/// 十进制 MB（1 MB = 1,000,000 字节），完整安装包实测见 [`MEASURED_INSTALLER_MB`]。
pub const INSTALLER_MB: f64 = 60.0;

/// 客户端界面进程的常驻内存，MB。
///
/// 跟 [`VOICE_CORE_RSS_MB`] 是**两个预算**：设计上留着「把 voice-core 拆成
/// 独立进程」这条路，那样两边各占各的。现在还在一个进程里，两条线加起来看。
///
/// 80 的依据是实测 59.4（见 [`MEASURED_UI_RSS_MB`]）加一档余量给字体缓存和
/// 几十条消息。作为对比，Electron 系的语音软件光界面就要两三百 MB。
pub const UI_RSS_MB: f64 = 80.0;

/// 客户端冷启动到窗口出现，毫秒。
///
/// 这条线是给**框架选型**用的，不是给用户感知用的 —— 用户一天启动一次，
/// 300 ms 和 800 ms 他分不出来。但它是个很灵敏的指标：一旦有人往启动路径上
/// 加了同步 IO、或者换了个重的界面框架，这个数第一个跳。
pub const UI_COLD_START_MS: f64 = 300.0;

// ===========================================================================
// 防回归闸：CI 卡的线，定在实测值 + 余量
// ===========================================================================

/// 协议链路嘴到耳 p95 的回归闸，毫秒。
///
/// M1 实测 46.5（city 档 / 10 ms 帧 / 缓冲 2 帧），留 8.5 ms 余量。
///
/// 为什么单独卡协议这一段：它是唯一**只跟我们的代码有关**的部分。
/// 设备那段由声卡和驱动决定，APM 那段由 libwebrtc 决定，
/// 这两段变了不是我们改坏了。协议段一旦变慢，一定是我们干的。
pub const GATE_PROTOCOL_MS: f64 = 55.0;

/// 端到端的回归闸，毫秒。M2 实测 91.9，留约 10% 余量。
///
/// 比 [`E2E_MS`] 严得多是故意的：产品线是「用户还能接受」，
/// 回归闸是「别比今天更差」。
pub const GATE_E2E_MS: f64 = 100.0;

/// 通话中 CPU 的回归闸，单核占比 %。实测 2.84（编解码 2.18 + APM 0.66）。
pub const GATE_CPU_PCT: f64 = 4.0;

/// 完整安装包的回归闸，十进制 MB。0.2.2 发布包 8.023011 MB，留约 25% 余量。
/// packaging/windows/check-size.ps1 读取此常量，release 打包超限即失败。
pub const GATE_INSTALLER_MB: f64 = 10.0;

// ===========================================================================
// M2 实测的分段，供各探针拿去算账
// ===========================================================================

/// WASAPI 采集 + 渲染吃掉的毫秒数。**M2 实测**，见 docs/m2-baseline.txt。
///
/// 拆开是：
/// - 采集 10.4 ms —— 一个引擎周期，WASAPI 的 QPC 时间戳直接量到的，没得选
/// - 渲染 20.0 ms —— 我们维持的队列深度，**这是个设计选择，不是物理限制**
///
/// 渲染那 20 ms 值得说清楚：物理下限是 10 ms（一个周期多一帧），实测零欠载。
/// 但那个工作点的余量只有一帧，线程漏醒一次就是一声咔哒 —— 而这软件是要跟
/// 游戏抢 CPU 的。取 20 ms 是为了留住整整一个周期的余量，扛得住漏醒一次。
///
/// 产品线放到 120 ms 之后，这 10 ms 已经买得起了 —— 不必再为了省它去冒咔哒的风险。
///
/// 注意这里存的是**实测值本身**，不带余量。余量只存在于 `GATE_*` 里 ——
/// 分段常量一旦掺了余量，端到端的账就对不上实际测出来的数了。
///
/// 数字来自一台机器（Ryzen 7 5700X3D + USB 声卡，共享模式引擎周期 10 ms）。
/// 虚拟声卡、蓝牙耳机都不在里面，它们只会更高。
pub const DEVICE_BUDGET_MS: f64 = 30.4;

/// APM（AEC3 + 降噪 + AGC2 + 高通）吃掉的毫秒数。**实测**。
///
/// 逐块：AEC3 单独 8.92 ms、降噪单独 6.92 ms、高通 0.92 ms、AGC2 0 ms，
/// 全开 14.92 ms。这里取整到 15.0 当预算 —— 预算不该追第三位小数，
/// 而且取整的方向是保守的那一边。
///
/// AEC3 和降噪都不可选：没有 AEC3 外放就啸叫，没有降噪机械键盘声直接糊到
/// 队友耳朵里。
pub const APM_BUDGET_MS: f64 = 15.0;

/// M1 实测的协议链路嘴到耳 p95，毫秒（city 档 / 10 ms 帧 / 缓冲 2 帧）。
pub const MEASURED_PROTOCOL_MS: f64 = 46.5;

/// M1 实测的 Opus 编解码 CPU，单核占比 %（complexity 5 / 10 ms 帧 / 单路）。
pub const MEASURED_CODEC_CPU_PCT: f64 = 2.18;

/// 实测的 APM CPU，单核占比 %（全开配置）。
///
/// 2026-09 把 APM 从 C++ 的 libwebrtc（M131）换成纯 Rust 的 sonora（M145）之后
/// 从 0.66 涨到这个数，见 docs/apm-backend.md。
pub const MEASURED_APM_CPU_PCT: f64 = 0.79;

/// 当前实测的通话 CPU 合计，单核占比 %。
pub const MEASURED_CPU_PCT: f64 = MEASURED_CODEC_CPU_PCT + MEASURED_APM_CPU_PCT;

/// 当前实测的端到端总延迟，毫秒。改动任何一段都要把这里更新掉。
pub const MEASURED_E2E_MS: f64 = MEASURED_PROTOCOL_MS + DEVICE_BUDGET_MS + APM_BUDGET_MS;

/// **实测**的自有链路延迟，毫秒 —— 分帧、编码器前瞻、加密、服务端转发、
/// 抖动缓冲、解码、混音走一整条，用啁啾做互相关量出来的（相关峰值 0.975）。
///
/// # 跟 [`MEASURED_PROTOCOL_MS`] 是两回事
///
/// M1 那个 46.5 ms 是在**注入过网络损伤**（同城档）的条件下量的，而且是把
/// 编解码和抖动缓冲单独搭起来测的，中间没有真的服务端、没有真的加密。
/// 这个 36.7 ms 是本机回环（网络时间≈0）、但**整条链路真的接起来**。
///
/// 两个数字都有用：46.5 告诉你网络占多少，36.7 告诉你我们自己占多少，
/// 而且确认了链路里没有藏着多余的缓冲 —— 实测只比理论下限大 0.2 ms。
///
/// **不含声卡**（合成设备一到节拍就交出整帧）**也不含 APM**。
pub const MEASURED_PIPELINE_MS: f64 = 36.7;

/// **实测**的回声抑制量，分贝。**合成的线性回路，不是真声学环境。**
///
/// 条件：类语音的宽带回声（带限到 300–3400 Hz 的噪声 × 音节包络），
/// 回声电平 −24 dB，回路延迟 30 ms。收敛之后稳定在这个数，残留 −82 dB。
///
/// # 这个数字不能当产品表现看
///
/// 测试里的回声路径是**纯线性**的 —— 延迟加衰减，没有音箱的非线性失真、
/// 没有削波、没有两个晶振的漂移。而恰恰是这些非线性的东西才真正区分 AEC
/// 实现的好坏。线性路径上自适应滤波器能收敛到近乎完美，所以这里量到的是
/// 「滤波器收敛得多好」，不是「外放开黑会不会啸叫」。
///
/// 真声学往返的测试写了（`apm_acoustic.rs`），但**还没有可信数字**：
/// 手上的麦克风都自带噪声门，那是非线性时变处理，而且在 APM 之前，
/// AEC 的线性滤波器学不了它。详见 docs/apm-backend.md。
///
/// 另外：残留的绝对电平比抑制量更接近「听不听得见」。AEC 压到一个固定底噪
/// 就到头了，所以回声越响抑制量的数字越好看 —— 只看比值会被这一点骗到。
///
/// （换 sonora 之前这个数是 26.0 dB / 残留 −50 dB。）
pub const MEASURED_AEC_DB: f64 = 57.9;

/// **实测**：没有回声时 AEC 对人声的损伤，分贝。
///
/// 这条比抑制量更要紧 —— 绝大多数人戴耳机，根本没有回声。
/// 开了 AEC 反而把他的声音削掉一截的话，这个功能就是负收益。
///
/// 换 sonora 之后从 0.2 涨到 1.1：它的抑制器两头都更激进，多消 32 dB 回声的
/// 同时也多削 0.9 dB 人声。离「听得出来」还很远，但方向要记住。
pub const MEASURED_AEC_HARM_DB: f64 = 1.1;

/// 实测的客户端界面进程常驻内存，MB。
///
/// 连上服务器、名单和频道树都画出来之后的稳定值，dist profile。
/// **不含音频那半边** —— 那一半见 [`MEASURED_CLIENT_IN_CHANNEL_RSS_MB`]。
/// M6 在登录页空闲时又量了一次，60.0，对得上。
pub const MEASURED_UI_RSS_MB: f64 = 59.4;

/// 实测的客户端**整个进程**常驻内存（工作集），MB：在频道里，有一个人一直在说话。
///
/// dist profile，60 秒平均。前台、最小化、收在托盘里三种状态差不到 0.2 MB ——
/// Windows 并没有在最小化时裁剪工作集（当初以为会）。量法和四种状态的完整表
/// 见 docs/measurements.md 的 M6 一节，原始输出存档在 docs/m6-footprint.txt，
/// 复现：`scripts\m6-footprint.ps1`。挂着 48 分钟，私有字节前后一半平均 56.71 / 56.70。
///
/// 含界面和音频两半，拿它跟 [`VOICE_CORE_RSS_MB`] 比是偏保守的。
pub const MEASURED_CLIENT_IN_CHANNEL_RSS_MB: f64 = 73.0;

/// 同上，私有字节（提交大小）。这才是真正占着的，工作集可能被系统换出去一部分。
pub const MEASURED_CLIENT_IN_CHANNEL_PRIVATE_MB: f64 = 57.0;

/// 实测的冷启动到窗口出现，毫秒（dist profile，三次取最差的稳态值）。
///
/// 第一次 220 ms 是磁盘缓存冷的，之后 79/92 ms。这里记稳态值：
/// 磁盘冷不冷不由我们决定。
pub const MEASURED_UI_COLD_START_MS: f64 = 92.0;

/// 实测的客户端可执行文件大小，MB（dist profile，strip 过）。
///
/// **还不是安装包**：打包器还没算。放在这里是为了让它在涨的时候看得见。
///
/// 这个数含 Opus 和 APM —— 2026-09 之前 APM 是默认关的，那时候量的 12.5 MB
/// 不含它。之后又加了提示音 / 念名字、自适应抖动缓冲，以及 C 运行库静态链接
/// （+0.2 MB，换来不再依赖 VCRUNTIME140.dll），到 15.01。
pub const MEASURED_CLIENT_EXE_MB: f64 = 15.01;

/// 0.2.2 正式 Release 的完整 Inno Setup 安装包：8,023,011 字节。
/// 十进制 MB，包含客户端、打包器与静态运行库；本地重打包可能略有差异。
pub const MEASURED_INSTALLER_MB: f64 = 8.023011;

/// 实测的服务端可执行文件大小，MB（dist profile，strip 过）。
///
/// 「单二进制、自部署零依赖」就是这个数。**不含音频那半边** ——
/// 服务端只转发 Opus 包，voice-core 是关掉默认 feature 引进来的，
/// 所以 APM 和 Opus 都没链进去。客户端大出来的那十几 MB 就是这些。
///
/// 2026-09 从 1.43 涨到 3.07：频道存档用的 SQLite 是整个编进来的（rusqlite
/// 的 `bundled`），+1.64 MB。换来的是自部署的人不用装任何数据库，
/// 以及封禁名单、角色这些以后要存的东西「写一半断电也不坏」。
///
/// 再到 3.25：C 运行库静态链接（+0.18 MB），不再依赖 VCRUNTIME140.dll。
pub const MEASURED_SERVER_EXE_MB: f64 = 3.25;

// ===========================================================================
// 不变量：编译期就检查
// ===========================================================================
//
// 这些是常量之间的关系，不是运行时行为 —— 所以用 const 断言，让它在**编译期**
// 就炸，而不是等到 `cargo test`。谁把闸调得比产品线还松、或者调到实测值以下，
// 当场编译失败，不可能悄悄合进去。
//
// 注意 const 里的 panic 消息只能是字面量，不能带格式化。

const _: () = assert!(GATE_E2E_MS < E2E_MS, "端到端的闸不该比产品线还松");
const _: () = assert!(GATE_CPU_PCT < CPU_PCT, "CPU 的闸不该比产品线还松");
const _: () = assert!(
    GATE_INSTALLER_MB < INSTALLER_MB,
    "安装包的闸不该比产品线还松"
);
const _: () = assert!(
    MEASURED_INSTALLER_MB < GATE_INSTALLER_MB,
    "安装包实测已经顶到闸了：重新测量后才能调整闸"
);

const _: () = assert!(
    MEASURED_PROTOCOL_MS < GATE_PROTOCOL_MS,
    "协议实测已经顶到闸了：要么是真的变慢了，要么该把闸重新定一次"
);
const _: () = assert!(
    MEASURED_E2E_MS < GATE_E2E_MS,
    "端到端实测已经顶到闸了：要么是真的变慢了，要么该把闸重新定一次"
);
const _: () = assert!(
    MEASURED_CPU_PCT < GATE_CPU_PCT,
    "CPU 实测已经顶到闸了：要么是真的变重了，要么该把闸重新定一次"
);

// 今天的实测值必须在产品线之内 —— 不然就是在承诺做不到的事。
const _: () = assert!(MEASURED_E2E_MS <= E2E_MS, "实测的端到端延迟超出了产品线");

const _: () = assert!(
    MEASURED_CLIENT_IN_CHANNEL_RSS_MB < VOICE_CORE_RSS_MB,
    "整个客户端在频道里的内存已经顶到 voice-core 的线了"
);
const _: () = assert!(
    MEASURED_CLIENT_IN_CHANNEL_PRIVATE_MB <= MEASURED_CLIENT_IN_CHANNEL_RSS_MB,
    "私有字节比工作集还大，多半是抄错了数"
);
const _: () = assert!(
    MEASURED_UI_RSS_MB < UI_RSS_MB,
    "界面内存实测已经顶到线了：要么是真的变重了，要么该重新定一次"
);
const _: () = assert!(
    MEASURED_UI_COLD_START_MS < UI_COLD_START_MS,
    "冷启动实测已经顶到线了：多半是有人往启动路径上加了同步 IO"
);
